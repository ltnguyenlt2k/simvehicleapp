'use client'

import { useState } from 'react'
import { Badge, Button, Checkbox, toast } from '@/components/emcn'
import type { SvProject } from '@/lib/api/contracts/sv'
import { cn } from '@/lib/core/utils/cn'
import { formatFileSize } from '@/lib/uploads/utils/file-utils'
import { AppActions } from '@/app/workspace/[workspaceId]/vehicle-projects/components/app-actions'
import { GeneratedFiles } from '@/app/workspace/[workspaceId]/vehicle-projects/components/generated-files'
import { useSvProjectSize, useUpdateSvProjectWorkflows } from '@/hooks/queries/sv-projects'
import { useSvWorkflowSettings } from '@/hooks/queries/sv-workflow-settings'

const STATUS = {
  creating: { label: 'Preparing…', variant: 'amber' },
  ready: { label: 'Ready', variant: 'green' },
  failed: { label: 'Failed', variant: 'red' },
} as const

/** Display names of the project languages. */
const LANGUAGE: Record<string, string> = { cpp: 'C++', python: 'Python', rust: 'Rust' }

/** `Updated 3 days ago` from epoch ms; coarse on purpose (the list is not live). */
function updatedAgo(at?: number): string | null {
  if (!at) return null
  const minutes = Math.max(0, Math.round((Date.now() - at) / 60_000))
  if (minutes < 1) return 'updated just now'
  if (minutes < 60) return `updated ${minutes} min ago`
  const hours = Math.round(minutes / 60)
  if (hours < 24) return `updated ${hours} h ago`
  const days = Math.round(hours / 24)
  return `updated ${days} day${days === 1 ? '' : 's'} ago`
}

interface ProjectCardProps {
  project: SvProject
  workspaceId: string
  workflows: { id: string; name: string }[]
  canEdit: boolean
}

/**
 * One vehicle app: status, language, VSS release, disk usage, assigned workflows (checkboxes), its generated
 * files and its lifecycle actions (ADR-0053). Workflows deleted from the workspace are not listed; an app with no
 * workflow left is marked unused.
 */
export function ProjectCard({ project, workspaceId, workflows, canEdit }: ProjectCardProps) {
  const updateWorkflows = useUpdateSvProjectWorkflows()
  const { data: size } = useSvProjectSize(project.id, project.status === 'ready')
  const [showFiles, setShowFiles] = useState(false)
  const existing = new Set(workflows.map((w) => w.id))
  const assigned = new Set(
    project.workflows
      .filter((w) => w.enabled && existing.has(w.simWorkflowId))
      .map((w) => w.simWorkflowId)
  )
  const status = STATUS[project.status]
  const details = [
    `/workspace/projects/${project.slug}`,
    LANGUAGE[project.language] ?? project.language,
    `VSS ${project.vssRelease}`,
    project.appName,
    size ? formatFileSize(size.bytes) : null,
    updatedAgo(project.updatedAt ?? project.createdAt),
  ].filter(Boolean)

  const toggle = (workflowId: string, on: boolean) => {
    const next = new Set(assigned)
    if (on) next.add(workflowId)
    else next.delete(workflowId)
    updateWorkflows.mutate(
      {
        projectId: project.id,
        workflowIds: workflows.map((w) => w.id).filter((id) => next.has(id)),
      },
      { onError: (e) => toast.error(e.message) }
    )
  }

  return (
    <div
      data-sv='project'
      data-sv-project={project.slug}
      className='flex flex-col gap-3 rounded-lg border border-[var(--border)] p-3'
    >
      <div className='flex items-center gap-2'>
        <span className='font-medium text-[14px] text-[var(--text-primary)]'>{project.name}</span>
        <Badge variant={status.variant} size='sm' data-sv='project-status'>
          {status.label}
        </Badge>
        {project.status === 'ready' && assigned.size === 0 && (
          <Badge variant='gray' size='sm' data-sv='project-unused'>
            Unused
          </Badge>
        )}
        <span className='min-w-0 truncate text-[12px] text-[var(--text-muted)]'>
          {details.join(' · ')}
        </span>
        <div className='ml-auto flex items-center gap-1'>
          <Button
            variant='ghost'
            size='sm'
            data-sv='project-files-toggle'
            disabled={project.status !== 'ready'}
            onClick={() => setShowFiles((v) => !v)}
          >
            {showFiles ? 'Hide files' : 'Generated files'}
          </Button>
          {canEdit && (
            <AppActions project={project} workspaceId={workspaceId} buildBytes={size?.buildBytes} />
          )}
        </div>
      </div>
      {project.status === 'failed' && project.statusMessage && (
        <p className='text-[12px] text-[var(--text-error)]'>{project.statusMessage}</p>
      )}
      <div className='flex flex-col gap-1'>
        <span className='text-[12px] text-[var(--text-secondary)]'>
          Workflows generated by SynCode
        </span>
        {workflows.length === 0 ? (
          <span className='text-[12px] text-[var(--text-muted)]'>
            No workflows in this workspace
          </span>
        ) : (
          <div className='flex flex-wrap gap-x-4 gap-y-1'>
            {workflows.map((w) => (
              <WorkflowOption
                key={w.id}
                projectId={project.id}
                projectRelease={project.vssRelease}
                workflow={w}
                checked={assigned.has(w.id)}
                disabled={!canEdit || updateWorkflows.isPending}
                onToggle={(on) => toggle(w.id, on)}
              />
            ))}
          </div>
        )}
      </div>
      {showFiles && <GeneratedFiles projectId={project.id} />}
    </div>
  )
}

interface WorkflowOptionProps {
  projectId: string
  projectRelease: string
  workflow: { id: string; name: string }
  checked: boolean
  disabled: boolean
  onToggle: (on: boolean) => void
}

/**
 * One workflow of the project: its VSS release next to the name. A workflow pinned to another release than
 * the project cannot be generated into it (SynCode fails with PROJECT_VSS_RELEASE_MISMATCH), so it cannot be
 * ticked — only unticked if it already is — and says why.
 */
function WorkflowOption({
  projectId,
  projectRelease,
  workflow,
  checked,
  disabled,
  onToggle,
}: WorkflowOptionProps) {
  const { data: settings } = useSvWorkflowSettings(workflow.id)
  const release = settings?.vssRelease ?? projectRelease
  const mismatch = release !== projectRelease
  const id = `sv-project-${projectId}-${workflow.id}`
  return (
    <label
      htmlFor={id}
      title={
        mismatch
          ? `${workflow.name} is designed on VSS ${release}; this project uses VSS ${projectRelease}. Change the workflow's VSS release in its editor, or use a ${release} project.`
          : undefined
      }
      className='flex items-center gap-1.5 text-[13px] text-[var(--text-primary)]'
    >
      <Checkbox
        id={id}
        size='sm'
        aria-label={`Generate ${workflow.name}`}
        data-sv-workflow={workflow.id}
        data-sv-release-mismatch={mismatch ? 'true' : undefined}
        checked={checked}
        disabled={disabled || (mismatch && !checked)}
        onCheckedChange={(v) => onToggle(v === true)}
      />
      {workflow.name}
      <span
        className={cn(
          'text-[12px]',
          mismatch ? 'text-[var(--text-error)]' : 'text-[var(--text-muted)]'
        )}
      >
        {mismatch ? `VSS ${release} — needs a ${release} project` : `VSS ${release}`}
      </span>
    </label>
  )
}
