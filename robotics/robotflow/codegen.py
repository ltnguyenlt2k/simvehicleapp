"""Deterministic native async Python emitter; returns a file set, never writes it."""
import copy
import hashlib
import json
import re

from jsonschema import Draft202012Validator
from compiler import Compiler,canonical,schema
from registry import load_registry
from units import UnitRegistry

VERSION='0.1.0'


def digest(value):return 'sha256:'+hashlib.sha256(value).hexdigest()
def text(value):return canonical(value).decode()+'\n'
def literal(value):return repr(json.loads(canonical(value)))


class Emitter:
    def __init__(self):
        self.counter=0;self.definitions=[]

    def region(self,body):
        name=f'_region_{self.counter:04d}';self.counter+=1
        lines=[f'async def {name}(ctx):']
        for statement in body:self.statement(lines,statement)
        lines.append('    return ctx.success()')
        self.definitions.append('\n'.join(lines))
        return name

    def statement(self,lines,statement):
        op=statement['op'];node=literal(statement['src']['nodeId'])
        prefix='    '
        line=lambda value,depth=1:lines.append(prefix*depth+value)
        if op in ('invoke','hold','stop','cancel','wait_until'):
            if op=='invoke':call=f'ctx.invoke({literal(statement["path"])}, {literal(statement["args"])}, timeout_ms={statement["timeoutMs"]})'
            elif op=='hold':call=f'ctx.hold({literal(statement["path"])}, {literal(statement["value"])}, duration_ms={statement["ms"]}, timeout_ms={statement["timeoutMs"]})'
            elif op=='cancel':call=f'ctx.cancel_body(timeout_ms={statement["timeoutMs"]})'
            elif op=='stop':call=f'ctx.stop(timeout_ms={statement["timeoutMs"]})'
            else:call=f'ctx.wait_until({literal(statement["condition"])}, timeout_ms={statement["timeoutMs"]})'
            line(f'async with ctx.node({node}, {op!r}) as _step:')
            line('_outcome = await '+call,2);line('_step.result(_outcome)',2)
            for index,phase in enumerate(sorted(statement['on'])):
                body=statement['on'][phase]
                handler=self.region(body)
                line(f'{"if" if index==0 else "elif"} _outcome.phase == {phase.upper()!r}:')
                line(f'_branch = await {handler}(ctx)',2)
                line('return ctx.combine(_outcome, _branch)',2)
            line('raise RuntimeError("unregistered operation outcome")')
        elif op=='if':
            yes=self.region(statement['then']);no=self.region(statement['else'])
            line(f'async with ctx.node({node}, "if") as _step:')
            line(f'_condition = await ctx.condition({literal(statement["condition"])})',2)
            line('_step.data(condition=_condition)',2)
            line('if _condition:');line(f'return await {yes}(ctx)',2)
            line('else:');line(f'return await {no}(ctx)',2)
        elif op=='loop':
            handler=self.region(statement['body'])
            line(f'async with ctx.node({node}, "loop") as _step:')
            if statement.get('forever'):
                line('_iteration = 0',2);line('while True:',2)
            else:line(f'for _iteration in range({statement["count"]}):',2)
            line('await ctx.checkpoint()',3)
            line(f'async with ctx.iteration({node}, _iteration):',3)
            line(f'_outcome = await {handler}(ctx)',4)
            line('if not _outcome.ok:',3);line('_step.result(_outcome)',4);line('return _outcome',4)
            if statement.get('forever'):line('_iteration += 1',3)
        elif op=='parallel':
            handlers=[self.region(body) for body in statement['children']]
            line(f'async with ctx.node({node}, "parallel") as _step:')
            line(f'_outcome = await ctx.parallel([{", ".join(handlers)}], mode={statement["mode"]!r})',2)
            line('_step.result(_outcome)',2)
            line('if not _outcome.ok:');line('return _outcome',2)
        else:
            line(f'async with ctx.node({node}, {op!r}):')
            if op=='noop':line('pass',2)
            elif op=='log':line(f'await ctx.log({statement["level"]!r}, {literal(statement["parts"])})',2)
            elif op=='wait':line(f'await ctx.wait({statement["ms"]})',2)
            elif op=='assign':line(f'await ctx.assign({literal(statement["name"])}, {literal(statement["value"])})',2)
            elif op=='read':line(f'await ctx.read({literal(statement["path"])}, {literal(statement["name"])})',2)
            elif op=='set_target':line(f'await ctx.set_target({literal(statement["path"])}, {literal(statement["value"])})',2)
            else:raise ValueError('unsupported IR operation '+op)

    def flow(self,ir,metadata):
        bindings=[]
        for behavior in ir['behaviors']:
            handler=self.region(behavior['body'])
            data={key:value for key,value in behavior.items() if key!='body'}
            bindings.append(literal(data)+f" | {{'handler': {handler}}}")
        header='# Generated by rflowc 0.1.0. Deterministic; edit the workflow source.\n'
        source=header+'\nFLOW_META = '+literal(metadata)+'\n\n'
        source+='\n\n'.join(self.definitions)+'\n\nBEHAVIORS = [\n'
        source+=''.join('    '+binding+',\n' for binding in bindings)+']\n'
        return source


def build_application(source,catalog,profile,registry=None,units=None,runtime_package_hash=None):
    registry=registry or load_registry();units=units or UnitRegistry()
    compiler=Compiler(source,catalog,profile,registry,units,'build')
    result=compiler.run()
    if not result['ok']:
        result['files']=None;return result
    if runtime_package_hash is not None and (not isinstance(runtime_package_hash,str)
            or not re.fullmatch(r'sha256:[a-f0-9]{64}',runtime_package_hash)):
        compiler.add('RF1001',field='runtimePackageHash',detail='verified runtime SHA256 required')
        result=compiler.result();result['files']=None;return result
    ir=result['ir']
    workflow={key:copy.deepcopy(compiler.graph[key]) for key in ('schema','rss','profile','vars')}
    workflow['nodes']=[dict(id=identity,block=item['block'],v=compiler.blocks[item['block']]['version'],props=copy.deepcopy(compiler.props[identity]))
        for identity,item in sorted(compiler.nodes.items())]
    workflow['edges']=sorted(copy.deepcopy(compiler.graph['edges']),key=lambda item:(tuple(item['from']),tuple(item['to'])))
    metadata=dict(compilerVersion=VERSION,runtimeVersion=ir['runtimeVersion'],workflowHash=digest(canonical(workflow)),
        irHash=ir['irHash'],catalogHash=ir['catalogHash'],profileId=ir['profile'],profileHash=ir['profileHash'],
        unitsHash=ir['unitsHash'],registryHash=registry.hash)
    if runtime_package_hash is not None:metadata['runtimePackageHash']=runtime_package_hash
    flow=Emitter().flow(ir,metadata)
    if len(flow.encode())>2*1024*1024:
        compiler.add('RF1002',field='nodes',detail='generated Python exceeds 2 MiB')
        result=compiler.result();result['files']=None;return result
    main=('from pathlib import Path\nfrom rfrt import run_app\n\n'
          'if __name__ == "__main__":\n    raise SystemExit(run_app(Path(__file__).resolve().parents[1]))\n')
    files={'app/__init__.py':'# RobotFlow generated application.\n','app/flow.py':flow,'app/main.py':main,
        'rfir.json':text(ir),'rss-catalog.json':text(catalog),'profile.json':text(compiler.profile),
        'units.v1.json':text(units.artifact()),'registry.json':text(registry.public()),'workflow.json':text(workflow)}
    hashes={path:digest(content.encode()) for path,content in sorted(files.items())}
    lock=dict(schema='rflow-lock.v1',**metadata,sourceHash=digest(canonical({path:value for path,value in hashes.items() if path.startswith('app/')})),files=hashes)
    lock['artifactHash']=digest(canonical(lock))
    Draft202012Validator(schema('rflow-lock.v1')).validate(lock)
    files['rflow.lock.json']=text(lock)
    result['files']=files
    return result
