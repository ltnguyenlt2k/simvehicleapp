 const traces=snapshot.logs.entries.filter(e=>e.text.startsWith('RFTRACE ')).map(e=>JSON.parse(e.text.slice(8)));
 const finished=id=>traces.filter(t=>t.event==='node_finished'&&t.nodeId===id&&t.data.phase==='SUCCEEDED').length;
